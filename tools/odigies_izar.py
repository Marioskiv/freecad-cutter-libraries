def fmt(x):
    return ("%.3f" % x).replace(".", ",")


def table(vc, rows, z):
    out = ["<table><tr><th>Ø</th><th>fz (mm/δόντι)</th><th>Στροφές</th><th>Πρόωση mm/min</th></tr>"]
    for d, fz in rows:
        rpm = vc * 1000 / (math.pi * d)
        out.append("<tr><td>%g</td><td>%s</td><td>%d</td><td>%d</td></tr>"
                   % (d, fmt(fz), round(rpm), round(rpm * fz * z)))
    return "".join(out) + "</table>"


