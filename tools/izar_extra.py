SHAPES = {"end": ("endmill.fcstd", "Endmill"), "ball": ("ballend.fcstd", "Ballend")}


def num(x): return ("%g" % x).replace(".", "_")
def mm(p, k): return float(p[k].split()[0])


out = sys.argv[1]
bitdir = os.path.join(out, "Bit"); libdir = os.path.join(out, "Library")
have, taken = set(), set()
for f in glob.glob(os.path.join(bitdir, "IZAR_*.fctb")):
    with open(f, encoding="utf-8") as b:
        p = json.load(b)["parameter"]
    name = os.path.basename(f)[:-5]
    have.add((name.split("_")[1], mm(p, "Diameter"), mm(p, "CuttingEdgeHeight")))
    taken.add(name)
total = 0
for lib_id, label, series in [("IZAR_235", "IZAR HSSE (κατάλογος 235) — συμπλήρωμα", I235),
                              ("IZAR_Carbide_2018", "IZAR σκληρομέταλλο 2018 — 2 δόντια γενικής χρήσης", C2018)]:
    tools = []
    for ser, tag, mat, shape, desc, rows in series:
        for D, d, L, l, art, art2, reach in rows:
            if (ser, float(D), float(l)) in have:
                continue
            # same diameter more than once in the series: name it by what differs (cutting length, length, reach)
            same = [r for r in rows if r[0] == D]
            bid = "IZAR_%s_%s" % (ser, num(D))
            if len(same) > 1 or bid in taken:
                if len({r[3] for r in same}) > 1:
                    bid += "_l%s" % num(l)
                if len({r[2] for r in same}) > 1 and len({(r[3], r[2]) for r in same}) > len({r[3] for r in same}):
                    bid += "_L%d" % L
                if reach and len({r[6] for r in same}) > 1:
                    bid += "_y%s" % num(reach)
                if bid in taken:
                    bid += "_l%s" % num(l)
            assert bid not in taken, bid
            taken.add(bid)
            name = "IZAR %s Ø%g 2Φ %s %s · l%g%s · art.%s%s" % (
                ser, D, tag, desc, l, (" · βάθος %g" % reach) if reach else "", art, (" / " + art2) if art2 else "")
            bit = {"attribute": {}, "id": bid, "name": name, "parameter": {
                "Chipload": "0.000 mm", "CuttingEdgeHeight": "%.3f mm" % l, "Diameter": "%.3f mm" % D, "Flutes": 2,
                "Length": "%.3f mm" % L, "Material": mat, "ShankDiameter": "%.3f mm" % d,
                "SpindleDirection": "Forward", "Units": "Metric"},
                "shape": SHAPES[shape][0], "shape-type": SHAPES[shape][1], "version": 2}
            with open(os.path.join(bitdir, bid + ".fctb"), "w", encoding="utf-8") as f:
                json.dump(bit, f, ensure_ascii=False, indent=2)
            tools.append(bid)
    lib = {"label": label, "tools": [{"nr": i + 1, "path": t + ".fctb"} for i, t in enumerate(tools)], "version": 1}
    with open(os.path.join(libdir, lib_id + ".fctl"), "w", encoding="utf-8") as f:
        json.dump(lib, f, ensure_ascii=False, indent=2)
    print(lib_id, len(tools))
    total += len(tools)
print(total, "bits")
